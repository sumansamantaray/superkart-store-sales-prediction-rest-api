from flask import Flask, request, jsonify
import joblib
import pandas as pd
import io

# Initialize the Flask application
app = Flask(__name__)

# Global variables for model and expected feature columns
model = None
expected_feature_columns = None

# Define the path to the saved model
MODEL_PATH = 'superkart_model.joblib' # Path relative to the app.py in the container

# Load the trained model and its features on application startup
try:
    loaded_artifacts = joblib.load(MODEL_PATH)
    model = loaded_artifacts['model']
    expected_feature_columns = loaded_artifacts['features']
    print(f"Model and features loaded successfully from {MODEL_PATH}")
except Exception as e:
    print(f"Error loading model or features: {e}")
    model = None # Set model to None if loading fails
    expected_feature_columns = None

# Define a simple home route (optional, for testing if the app is running)
@app.route('/')
def home():
    return "SuperKart Sales Prediction API is running!"

# Function to preprocess a single input record (should match training preprocessing)
def preprocess_single_input(data_dict):
    df = pd.DataFrame([data_dict])

    # Feature Engineering: Store_Age_Years
    CURRENT_YEAR = 2026 # Must match the year used during training
    if 'Store_Establishment_Year' in df.columns:
        df['Store_Age_Years'] = CURRENT_YEAR - df['Store_Establishment_Year']
        df.drop('Store_Establishment_Year', axis=1, inplace=True)

    # Drop 'Product_Id_char' and 'Product_Type_Category' if they were present in raw input but not in model features
    # These were likely intermediate features in the notebook but not part of the final X_train
    if 'Product_Id_char' in df.columns:
        df.drop('Product_Id_char', axis=1, inplace=True)
    if 'Product_Type_Category' in df.columns:
        df.drop('Product_Type_Category', axis=1, inplace=True)

    # Use the globally loaded expected_feature_columns
    global expected_feature_columns
    if expected_feature_columns is None:
        raise ValueError("Expected feature columns not loaded during app startup. Model loading failed.")

    expected_columns = expected_feature_columns

    # Create a DataFrame with all expected columns, initialized to 0
    processed_df = pd.DataFrame(0, index=[0], columns=expected_columns)

    # Populate numerical features (including engineered Store_Age_Years)
    numerical_features = ['Product_Weight', 'Product_Allocated_Area', 'Product_MRP', 'Store_Age_Years']
    for col in numerical_features:
        if col in df.columns:
            processed_df[col] = df[col].values

    # Populate one-hot encoded categorical features
    # This part requires careful handling to match the columns generated by get_dummies during training
    for original_col in ['Product_Sugar_Content', 'Product_Type', 'Store_Id', 'Store_Size', 'Store_Location_City_Type', 'Store_Type']:
        if original_col in df.columns:
            value = str(df[original_col].iloc[0]) # Convert to string to handle potential non-string values
            # For Product_Sugar_Content, 'reg' was unified to 'Regular'
            if original_col == 'Product_Sugar_Content' and value.lower() == 'reg':
                value = 'Regular'

            encoded_col_name = f"{original_col}_{value}"
            if encoded_col_name in processed_df.columns:
                processed_df[encoded_col_name] = 1

    # Ensure column order matches expected_columns
    processed_df = processed_df[expected_columns]
    return processed_df

# Function to preprocess a batch DataFrame
def preprocess_batch_data(input_df):
    df = input_df.copy()

    # Feature Engineering: Store_Age_Years
    CURRENT_YEAR = 2026 # Must match the year used during training
    if 'Store_Establishment_Year' in df.columns:
        df['Store_Age_Years'] = CURRENT_YEAR - df['Store_Establishment_Year']
        df.drop('Store_Establishment_Year', axis=1, inplace=True)

    # Drop 'Product_Id_char' and 'Product_Type_Category'
    if 'Product_Id_char' in df.columns:
        df.drop('Product_Id_char', axis=1, inplace=True)
    if 'Product_Type_Category' in df.columns:
        df.drop('Product_Type_Category', axis=1, inplace=True)

    # Unify 'reg' with 'Regular' in Product_Sugar_Content for batch data
    if 'Product_Sugar_Content' in df.columns:
        df['Product_Sugar_Content'] = df['Product_Sugar_Content'].replace('reg', 'Regular')

    # One-hot encode categorical features
    categorical_cols_to_encode = [col for col in ['Product_Sugar_Content', 'Product_Type', 'Store_Id', 'Store_Size', 'Store_Location_City_Type', 'Store_Type'] if col in df.columns]
    df_encoded = pd.get_dummies(df, columns=categorical_cols_to_encode, drop_first=True)

    # Use the globally loaded expected_feature_columns
    global expected_feature_columns
    if expected_feature_columns is None:
        raise ValueError("Expected feature columns not loaded during app startup. Model loading failed.")

    expected_columns = expected_feature_columns

    # Add missing columns (from expected_columns) to df_encoded and fill with 0
    missing_cols = set(expected_columns) - set(df_encoded.columns)
    for c in missing_cols:
        df_encoded[c] = 0

    # Ensure column order matches expected_columns
    processed_df = df_encoded[expected_columns]
    return processed_df


@app.route('/v1/predict', methods=['POST'])
def predict():
    if model is None:
        return jsonify({'error': 'Model not loaded'}), 500
    if expected_feature_columns is None:
        return jsonify({'error': 'Expected feature columns not available'}), 500

    try:
        data = request.get_json(force=True)
        processed_data = preprocess_single_input(data)
        prediction = model.predict(processed_data)[0]
        return jsonify({'prediction': prediction.item()}) # .item() to convert numpy float to Python float
    except Exception as e:
        return jsonify({'error': str(e)}), 400

@app.route('/v1/predictbatch', methods=['POST'])
def predict_batch():
    if model is None:
        return jsonify({'error': 'Model not loaded'}), 500
    if expected_feature_columns is None:
        return jsonify({'error': 'Expected feature columns not available'}), 500

    try:
        # Assuming the batch data comes as a CSV file in the request files
        if 'file' not in request.files:
            return jsonify({'error': 'No file part in the request'}), 400

        file = request.files['file']
        if file.filename == '':
            return jsonify({'error': 'No selected file'}), 400

        if file and file.filename.endswith('.csv'):
            # Read the CSV data directly from the file stream
            batch_df = pd.read_csv(io.StringIO(file.stream.read().decode('utf-8')))
            processed_batch_data = preprocess_batch_data(batch_df)
            batch_predictions = model.predict(processed_batch_data)
            # Convert numpy array to list for JSON serialization
            return jsonify({'predictions': batch_predictions.tolist()})
        else:
            return jsonify({'error': 'Invalid file format, please upload a CSV'}), 400

    except Exception as e:
        return jsonify({'error': str(e)}), 400
